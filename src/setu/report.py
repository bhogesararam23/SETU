"""Render a run as a human-readable validation report.

Two outputs, deliberately: results/validation.json for machines and the
dashboard, results/VALIDATION.md for people. The markdown is written to lead
with what did not work, because a report that opens with its own strengths is
read as marketing and this one is not.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

RESULTS_DIR = Path(__file__).resolve().parents[2] / "results"

#: Kept here rather than in prose so a report cannot accidentally attribute the
#: wrong standard to the action level it used. Rajkot's pilot runs at the WHO
#: guideline, not the NAAQS limit, and saying "NAAQS" next to 15 ug/m3 would be
#: a factual error a reviewer is entitled to catch.
NAAQS_PM25_24H_UGM3 = 60.0
WHO_PM25_24H_UGM3 = 15.0


def mean_of(rows: list[dict], path: str) -> float | None:
    vals = []
    for r in rows:
        node: Any = r
        for key in path.split("."):
            if not isinstance(node, dict) or key not in node:
                node = None
                break
            node = node[key]
        if isinstance(node, (int, float)):
            vals.append(float(node))
    return sum(vals) / len(vals) if vals else None


def _fmt(v: float | None, dp: int = 3) -> str:
    return "n/a" if v is None else f"{v:.{dp}f}"


def standard_for(level: float) -> str:
    """Name the standard an action level corresponds to.

    Shared with the operator console so the screen and the report cannot call the
    same number by two different statutory names."""
    return {
        NAAQS_PM25_24H_UGM3: "India NAAQS 24-hour limit",
        WHO_PM25_24H_UGM3: "WHO 2021 24-hour guideline",
    }.get(float(level), "operator-set action level")


def calibration_summary(rows: list[dict]) -> dict:
    """Run-wide means, which is what the console's validation panel is claiming
    to show. Averaging one node's row and labelling it "Calibration MAE" was a
    real defect: node rajkot-00 scores 14.70 -> 0.28 ug/m3 while the 40-node mean
    is 9.85 -> 1.82, so the screen read far better than the report beside it."""
    keys = ("mae", "rmse", "nmae", "r2", "bias", "threshold_accuracy")
    out = {"nodes": len(rows)}
    for key in keys:
        out[f"before_{key}"] = mean_of(rows, f"before.{key}")
        out[f"after_{key}"] = mean_of(rows, f"after.{key}")
    out["interval_coverage"] = mean_of(rows, "interval_coverage")
    out["mean_sigma"] = mean_of(rows, "mean_sigma")
    return out


def headline(summary: dict) -> str:
    """The one line that says what a run was."""
    level = float(summary["threshold_ugm3"])
    standard = standard_for(level)
    return (f"Generated by `python -m setu run`. Site **{summary['site']}**, "
            f"{summary['nodes']} nodes, {summary['hours']} hours of background, "
            f"action level {level:.0f} ug/m3 PM2.5 ({standard}). For reference: "
            f"the NAAQS 24-hour limit is {NAAQS_PM25_24H_UGM3:.0f} ug/m3 and the "
            f"WHO 2021 24-hour guideline is {WHO_PM25_24H_UGM3:.0f} ug/m3.")


def calibration_rows(summary: dict) -> list[tuple[str, str]]:
    """Metric labels paired with their JSON path, with the decision threshold
    named in the label. "threshold accuracy 0.93" without saying *which*
    threshold is not a number anyone can check."""
    return [
        ("MAE ug/m3", "mae"),
        ("RMSE ug/m3", "rmse"),
        ("nMAE", "nmae"),
        ("R^2", "r2"),
        ("bias ug/m3", "bias"),
        (f"threshold accuracy @ {float(summary['threshold_ugm3']):.0f} ug/m3",
         "threshold_accuracy"),
    ]


def _missing(value) -> bool:
    """True for None and NaN alike.

    signature_agreement() emits None for a channel the node does not measure,
    but the pandas round-trip coerces None to NaN inside a float column - so
    every downstream check has to treat the two as the same absence, or the
    report prints '+nan' where it means 'not measured'.
    """
    return value is None or (isinstance(value, float) and value != value)


def _jsonable(obj):
    """Replace NaN/inf with None so the payload is strict JSON.

    NaN is not valid JSON: json.dumps writes it verbatim and the browser's
    JSON.parse refuses it, so a single unmeasured channel used to make the
    whole operator console unreadable. Null is the honest encoding of 'no
    number here' and every consumer already handles it.
    """
    if isinstance(obj, dict):
        return {k: _jsonable(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_jsonable(v) for v in obj]
    if isinstance(obj, float) and (obj != obj or obj in (float("inf"), float("-inf"))):
        return None
    return obj


def to_json(result, directory: Path = RESULTS_DIR) -> Path:
    directory.mkdir(parents=True, exist_ok=True)
    payload = {
        "summary": result.summary,
        "provenance": result.provenance,
        "calibration": result.calibration,
        "transfer": result.transfer,
        "attribution": result.attribution,
        "forecast": result.forecast,
        "response": {k: v for k, v in result.response.items()
                     if k != "sample_actions"},
        "sample_actions": result.response.get("sample_actions", [])[:40],
        "drift": result.drift,
        "shares": result.shares,
        "equal_cost": result.equal_cost,
    }
    path = directory / "validation.json"
    path.write_text(json.dumps(_jsonable(payload), indent=2, default=str),
                    encoding="utf-8")
    return path


def to_markdown(result, directory: Path = RESULTS_DIR) -> Path:
    directory.mkdir(parents=True, exist_ok=True)
    s = result.summary
    prov = result.provenance
    att = result.attribution
    cal = result.calibration

    lines: list[str] = []
    add = lines.append

    add("# SETU - validation report")
    add("")
    add(headline(s))
    add("")

    add("## What this run can and cannot support")
    add("")
    add("| Claim | Supported? | Why |")
    add("| --- | --- | --- |")
    add("| The calibration maths recovers a known signal | **Yes** | "
        "Ground truth is known by construction in the twin |")
    add("| The attribution separates sources by size mode | **Yes, partially** | "
        f"{att['accuracy']:.1%} accuracy on {att['scorable_hours']:,} node-hours "
        f"against {_fmt(att['chance'], 2)} chance |")
    failing_shares = [row["source"] for row in result.shares if not row["within"]]
    share_verdict = (f"**No, fails for {', '.join(failing_shares)}**"
                     if failing_shares else "**Within bands**")
    add(f"| The absolute source shares match receptor studies | {share_verdict} | "
        "The twin's injection rates were tuned to a published apportionment, "
        "so the shares measure the tuned twin, not the city - see the shares "
        "table and docs/LIMITATIONS.md |")
    add("| The error figures are instrument-compliance results | **No** | "
        "The reference is CAMS reanalysis at ~10 km, not a beta-gauge station. "
        "CPCB was unreachable from the development network |")
    add("| Triggering beats a fixed roster at equal cost | **Conditionally** | "
        "Only when the lever is short-lived and the source is episodic; both "
        "null results are shown below |")
    add("")

    add("## 1. Calibration")
    add("")
    add("| Metric | Raw sensor | Calibrated |")
    add("| --- | --- | --- |")
    for label, key in calibration_rows(s):
        before = mean_of(cal, f"before.{key}")
        after = mean_of(cal, f"after.{key}")
        add(f"| {label} | {_fmt(before, 2)} | {_fmt(after, 2)} |")
    add("")
    add(f"Mean MAE reduction across {len(cal)} nodes: "
        f"{100 * (1 - (mean_of(cal, 'after.mae') or 0) / (mean_of(cal, 'before.mae') or 1)):.1f}%")
    add(f"(Bush et al., AMT 15:3261, 2022 report 37-94% for the same method family.)")
    add("")
    cover = mean_of(cal, "interval_coverage")
    add(f"Interval coverage **{_fmt(cover)}** against a nominal 0.80 for a 10th-90th "
        "quantile band. This is the number that makes the response engine's "
        "uncertainty gate meaningful rather than decorative: the gate refuses to "
        "dispatch while the interval straddles the threshold, and that only "
        "protects anyone if the interval is honest.")
    add("")

    if result.transfer.get("nodes_transferred"):
        add("## 2. Calibration transfer (nodes that never saw a reference)")
        add("")
        t = result.transfer
        add(f"{t['nodes_transferred']} nodes calibrated by pair-based transfer from "
            f"a co-located donor. Mean overlap R^2 {_fmt(t['mean_overlap_r2'])}, "
            f"mean MAE {_fmt(t['mean_mae_before'], 2)} -> "
            f"{_fmt(t['mean_mae_after'], 2)} ug/m3.")
        add("")
        add("This is what lets coverage scale without a reference station on every "
            "pole - the bottleneck the whole project exists to get around.")
        add("")

        bands = t.get("by_distance_band") or []
        if bands:
            add("The claim worth attacking is not that transfer works, but that it "
                "works *away from the donor*. Scored by donor distance:")
            add("")
            add("| Donor distance | Nodes | Mean distance | MAE raw | MAE transferred | Overlap R^2 |")
            add("| --- | --- | --- | --- | --- | --- |")
            for b in bands:
                add(f"| {b['band']} | {b['nodes']} | {b['mean_distance_m']:.0f} m | "
                    f"{_fmt(b['mean_mae_before'], 2)} | {_fmt(b['mean_mae_after'], 2)} | "
                    f"{_fmt(b['mean_overlap_r2'])} |")
            add("")
            corr = t.get("distance_mae_correlation")
            if corr is not None:
                add(f"Pearson r between donor distance and post-transfer MAE: "
                    f"**{corr:+.3f}** across "
                    f"{t['nodes_transferred']} nodes, out to "
                    f"{_fmt(t.get('max_donor_distance_m'), 0)} m. A large positive "
                    f"value would mean the transfer is really a co-location effect "
                    f"wearing a longer hat; this is the number that would show it.")
            else:
                add("Distance-variance too small to correlate - every transferred "
                    "node sits at a similar range from its donor, so this run cannot "
                    "answer the distance question either way.")
            add("")

    add("## 3. Attribution")
    add("")
    add(f"- Classes: {', '.join(att['classes'])}")
    add(f"- Accuracy on scorable node-hours: **{att['accuracy']:.3f}** "
        f"(chance {_fmt(att['chance'], 2)}) over {att['scorable_hours']:,} hours")
    add(f"- Accuracy where the posterior exceeds 0.60: **{att['accuracy_above_060']:.3f}** "
        f"on {att['share_of_hours_above_060']:.1%} of hours")
    add(f"- Multinomial log loss: {_fmt(att['log_loss'], 4)}")
    add(f"- Hours the posterior floor declined to name: "
        f"**{att.get('abstained', 0.0):.1%}** - the gate refusing to guess is "
        "the gate doing its job, not a gap in the data")
    bg = att.get("background_rejection") or {}
    if bg.get("hours"):
        add(f"- On the {bg['hours']:,} held-out hours the twin labelled "
            f"background or mixed - nothing injected, or no single source won "
            f"- the model declined **{bg['declined']:.1%}** and named a source "
            f"on the rest. The {bg['misnamed']:.1%} misnamed is the "
            "confabulation the reject class exists to shrink, and it is the "
            "share by which the absolute numbers below are flattered if read "
            "as a city apportionment.")
    add("")
    add("### Sign check against the published physics")
    add("")
    add("A classifier can reach good accuracy through a spurious correlation. "
        "These signs are the ones the literature requires:")
    add("")
    sc = att["sign_check"]
    add("| Feature | Expected | Learned |")
    add("| --- | --- | --- |")
    add(f"| coarse/accumulation count ratio on road dust | positive | "
        f"{sc['coarse_count_ratio_on_dust']:+.3f} |")
    add(f"| coarse/accumulation count ratio on open burning | negative | "
        f"{sc['coarse_count_ratio_on_burning']:+.3f} |")
    add(f"| relative humidity on secondary aerosol | positive | "
        f"{sc['rh_on_secondary']:+.3f} |")
    add("")

    agreement = att.get("signature_agreement") or {}
    pairs = agreement.get("pairs") or []
    if pairs:
        add(f"Scored systematically rather than three at a time: of "
            f"{agreement.get('checked', 0)} declared directions the node can "
            f"actually test, **{agreement.get('agreed', 0)} agree** "
            f"({_fmt(agreement.get('rate'), 2)}). The disagreements are all "
            "reported below rather than tuned away, because a coefficient "
            "that contradicts the published signature is a finding about the "
            "model or the twin, and which one it is has to be argued, not "
            "hidden.")
        add("")
        add("| Source | Declared channel | Expected | Learned | Strength | Note |")
        add("| --- | --- | --- | --- | --- | --- |")
        for p in pairs:
            if p["agrees"] is None:
                learned = ("-" if _missing(p["coefficient"])
                           else f"{p['coefficient']:+.3f}")
                add(f"| {p['source']} | {p['signature_feature']} | "
                    f"{p['direction']} | {learned} | {p['strength']:.2f} | "
                    f"{p['note'] or 'not judged'} |")
        for p in pairs:
            if p["agrees"] is False:
                add(f"| {p['source']} | {p['signature_feature']} | "
                    f"{p['direction']} | {p['coefficient']:+.3f} | "
                    f"{p['strength']:.2f} | **disagrees** |")
        add("")

    importance = att.get("feature_importance") or []
    if importance:
        add("### What the answer rests on")
        add("")
        add("Permutation importance on held-out hours: how much accuracy the "
            "model loses when one channel is shuffled out of the row. Scored "
            "out of sample, so this describes what the prediction depends on "
            "rather than what the fit memorised. A sign can be right and the "
            "feature still worthless - this is the table that separates the "
            "two.")
        add("")
        add("| Channel | Accuracy drop | Repeat sigma |")
        add("| --- | --- | --- |")
        for row in importance:
            add(f"| {row['feature']} | {row['importance_mean']:+.3f} | "
                f"{row['importance_std']:.3f} |")
        add("")

    reliability = att.get("confidence_calibration") or {}
    bins = reliability.get("bins") or []
    if bins:
        add("### Is the posterior worth gating on?")
        add("")
        add("Every gate downstream is phrased as a probability, so the "
            "probability has to mean what it says. Held-out hours binned by "
            "the top-class posterior:")
        add("")
        add("| Posterior bin | Hours | Mean confidence | Accuracy | Gap |")
        add("| --- | --- | --- | --- | --- |")
        for b in bins:
            add(f"| {b['bin_lo']:.2f}-{b['bin_hi']:.2f} | {b['n']:,} | "
                f"{b['mean_confidence']:.3f} | {b['accuracy']:.3f} | "
                f"{b['gap']:.3f} |")
        add("")
        ece = reliability.get("ece")
        add(f"Expected calibration error **{_fmt(ece, 3)}**. A gate at "
            "0.45 or 0.60 is only as strict as the bin it sits in: where the "
            "gap is positive the model is more sure than it should be, which "
            "makes every posterior floor slightly more permissive than its "
            "label, and the number above is what that costs.")
        add("")

    failing = [row["source"] for row in result.shares if not row["within"]]
    title = "### Share cross-check against receptor studies"
    add(title + (f" - FAILS for {', '.join(failing)}" if failing else ""))
    add("")
    add("| Source | SETU share | Published range | Within? |")
    add("| --- | --- | --- | --- |")
    for row in result.shares:
        add(f"| {row['source']} | {row['setu_share']:.3f} | "
            f"{row['published_low']:.2f}-{row['published_high']:.2f} | "
            f"{'yes' if row['within'] else '**no**'} |")
    add("")
    if failing:
        add(f"{', '.join(failing)} falls outside its band, and the cause is "
            "read off the twin before the classifier: the injection rates "
            "decide how many hours each source wins, and a classifier cannot "
            "name a source for hours that were never injected. Within-class "
            "discrimination is measured above and holds regardless.")
    else:
        add("Every source sits inside the band its published evidence sets. "
            "That is a weaker statement than it looks and a stronger one than "
            "it used to be. The twin's injection rates were tuned to a "
            "published apportionment, so this check now says the classifier "
            "recovers what was put in, within the bands receptor studies "
            "measure - a real test of discrimination, and still no evidence "
            "about the city's actual shares, which is the same honesty the "
            "rest of the twin asks for. An earlier run failed here for road "
            "dust and traffic, and docs/LIMITATIONS.md records why.")
    add("")

    add("## 4. Forecast skill")
    add("")
    add("| Horizon | n | Model RMSE | Persistence RMSE | Skill | R^2 |")
    add("| --- | --- | --- | --- | --- | --- |")
    for row in sorted(result.forecast, key=lambda r: r["horizon_h"]):
        add(f"| {row['horizon_h']}h | {row['n']:,} | {_fmt(row['model_rmse'], 2)} | "
            f"{_fmt(row['persistence_rmse'], 2)} | "
            f"{_fmt(row['skill_vs_persistence'], 3)} | {_fmt(row['model_r2'], 3)} |")
    add("")
    add("Relative skill rises with horizon because the persistence baseline "
        "degrades faster than the model does. Absolute RMSE grows monotonically. "
        "Chen et al., Sci. Rep. 14 (2024) report RMSE 19.11 at 7h on dense "
        "reference networks; these figures are 40 low-cost nodes on a 320 m grid "
        "and are not comparable to them.")
    add("")

    add("## 5. Response engine")
    add("")
    r = result.response
    add(f"- Dispatches: **{r['actions']}**")
    add(f"- Suppressed: **{r['suppressed']}**")
    if r["actions"] == 0:
        add("")
        add(f"This window produced no dispatches, and that is the correct "
            f"answer for this validation window: background PM2.5 over "
            f"{s['hours']} hours averaged {s['background_mean_pm25']} ug/m3 and "
            f"peaked at {s['background_max_pm25']}, against an action level of "
            f"{s['threshold_ugm3']:.0f} ug/m3. Rajkot's monsoon and post-monsoon "
            f"months are clean enough that the 24-hour standard is not reached. "
            f"Run `python -m setu check` to drive the engine at the WHO 24-hour "
            f"guideline of 15 ug/m3 instead, or re-run against a November window "
            f"once it is available.")
    add(f"- Zones tracked: {r['zones_tracked']}")
    add(f"- Human sign-off required: {r['signoff_required']}")
    add("")
    add("| Gate that stopped it | Count |")
    add("| --- | --- |")
    for reason, count in sorted(r["suppressed_by_reason"].items(),
                                key=lambda kv: -kv[1]):
        add(f"| {reason} | {count} |")
    add("")
    add("The suppression ledger is the point of this table. A dispatcher who "
        "receives the same alert forty times in a night stops reading it, so the "
        "gates have to be auditable for what they cost as well as what they "
        "prevented.")
    add("")

    add("## 6. Does triggering beat a roster, at equal cost?")
    add("")
    add("Both arms get the same number of passes per day. The roster spaces them "
        "from a 05:00 shift start; the trigger places them on the hours the grid "
        "actually breaches.")
    add("")
    ec = result.equal_cost
    if ec.get("note"):
        add(ec["note"])
    else:
        add(f"Basis: hours where the coarse fraction cleared "
            f"{ec.get('coarse_action_ugm3', 30):.0f} ug/m3 and the attributed "
            f"source was road dust or construction - "
            f"{len(ec.get('breach_hours', []))} distinct hours in this window. "
            f"The engine above was driven at "
            f"{ec.get('action_threshold_ugm3', 60):.0f} ug/m3.")
    add("")
    add("| Lever (effective window) | Roster coverage | Triggered | Gain |")
    add("| --- | --- | --- | --- |")
    labels = {
        "sprinkling_62min": "Water sprinkling, 62 min",
        "sweeping_150min": "Vacuum sweeping, 150 min",
        "suppressant_20h": "CaCl2 suppressant, ~20 h",
    }
    for key, row in result.equal_cost.items():
        if not isinstance(row, dict) or "roster_coverage" not in row:
            continue
        add(f"| {labels.get(key, key)} | {row['roster_coverage']:.2f} | "
            f"{row['triggered_coverage']:.2f} | {row['gain']:+.2f} |")
    add("")
    add("The suppressant row is the honest one. A lever that lasts a day does not "
        "care where you put it, so triggering earns nothing there.")
    add("")
    road = ec.get("road_dust_continuous_profile")
    if road:
        add(f"Scored instead on continuously road-proximate dust, present across "
            f"{len(road.get('breach_hours', []))} hours a day, the gain is "
            f"{road['sprinkling_62min']['gain']:+.2f}. That is the unfavourable "
            f"case and it is stated rather than omitted: where a source runs "
            f"around the clock, no placement strategy helps and the only lever "
            f"that does is a longer-lived one. Triggering pays off on the "
            f"episodic sources - construction campaigns and burning nights - "
            f"and not on the chronic one.")
    else:
        add("The continuously-road-dust variant produced no scorable hours in "
            "this window.")
    add("")

    add("## 7. Drift and quarantine")
    add("")
    d = result.drift
    add(f"{d['nodes_with_alarms']} of {s['nodes']} nodes raised a CUSUM alarm "
        "against their own calibration residual.")
    if s.get("quarantined"):
        add("")
        add("Quarantined: " + ", ".join(s["quarantined"]))
    add("")
    quarantined = len(s.get("quarantined", []))
    if quarantined > s["nodes"] * 0.5:
        add("")
        add(f"**This is a finding, not a passing grade.** More than half the grid "
            f"tripped its drift monitor within the evaluation window. The "
            f"calibration was fitted on the monsoon and scored on the post-monsoon "
            f"period, and the residual relationship moved with it - so a "
            f"four-month-old calibration does not survive a season change. "
            f"Operationally that means recalibration is periodic, not one-off. "
            f"The cost stays low because only the co-location step needs a vehicle: "
            f"one reference visit refreshes every node transferred from it.")
    add("")
    add("Drift is the documented reason CPCB does not accept low-cost data for "
        "regulatory use, so a monitor that cannot notice its own decay is not "
        "deployable regardless of its initial accuracy.")
    add("")

    add("## Provenance")
    add("")
    for rec in prov.get("background", []):
        add(f"- `{rec['label']}` fetched {rec['fetched_at_iso']} "
            f"({'cache' if rec['from_cache'] else 'live'})")
    add(f"- Background grid: {prov.get('grid_deg')} deg "
        f"(CAMS global ensemble), {prov.get('hourly_rows')} hours, "
        f"{prov.get('dropped_incomplete_hours')} dropped for missing meteorology")
    inj = prov.get("injected", {})
    add(f"- Twin: seed {inj.get('seed')}, {inj.get('dust_event_hours')} dust-event "
        f"hours, {inj.get('burning_event_hours')} burning-event hours, "
        f"{inj.get('dead_nodes')} dead nodes, {inj.get('obstructed_nodes')} "
        f"obstructed, {inj.get('drifting_nodes')} drifting")
    add("")
    add("**Every concentration produced by the twin is simulated.** The background "
        "it is derived from is real and hourly; the grid is not, because the "
        "hardware does not exist yet.")
    add("")

    path = directory / "VALIDATION.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def evidence_pack(action: dict, directory: Path = RESULTS_DIR) -> Path:
    """One folder-ready JSON per dispatch, for the enforcement officer."""
    directory.mkdir(parents=True, exist_ok=True)
    out = directory / "evidence" / f"{action['id']}.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(action, indent=2, default=str), encoding="utf-8")
    return out
